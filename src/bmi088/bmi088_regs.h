/* BMI088 register map, both dies. Datasheet BST-BMI088-DS001. */
#ifndef BMI088_REGS_H
#define BMI088_REGS_H

#define BMI088_REG_CHIP_ID			0x00

#define BMI088_ACCEL_CHIP_ID			0x1e
#define BMI088_ACCEL_REG_ERR			0x02
#define BMI088_ACCEL_REG_STATUS			0x03
#define BMI088_ACCEL_REG_DATA			0x12
#define BMI088_ACCEL_REG_TEMP			0x22
#define BMI088_ACCEL_REG_CONF			0x40
#define BMI088_ACCEL_REG_RANGE			0x41
#define BMI088_ACCEL_REG_PWR_CONF		0x7c
#define BMI088_ACCEL_REG_PWR_CTRL		0x7d
#define BMI088_ACCEL_REG_SOFT_RESET		0x7e

#define BMI088_ACCEL_ERR_MASK			0x1d
#define BMI088_ACCEL_STATUS_DRDY		0x80
#define BMI088_ACCEL_RANGE_MASK			0x03
#define BMI088_ACCEL_CONF_MASK			0xff
#define BMI088_ACCEL_PWR_SUSPEND		0x03
#define BMI088_ACCEL_PWR_ACTIVE			0x00
#define BMI088_ACCEL_DISABLE			0x00
#define BMI088_ACCEL_ENABLE			0x04

#define BMI088_GYRO_CHIP_ID			0x0f
#define BMI088_GYRO_REG_DATA			0x02
#define BMI088_GYRO_REG_STATUS			0x0a
#define BMI088_GYRO_REG_RANGE			0x0f
#define BMI088_GYRO_REG_BANDWIDTH		0x10
#define BMI088_GYRO_REG_SOFT_RESET		0x14
#define BMI088_GYRO_REG_INT_CTRL		0x15

#define BMI088_GYRO_STATUS_DRDY			0x80
#define BMI088_GYRO_RANGE_MASK			0x07
#define BMI088_GYRO_BANDWIDTH_MASK		0x0f
#define BMI088_GYRO_DRDY_ENABLE			0x80

#define BMI088_SOFT_RESET_COMMAND		0xb6

#endif /* BMI088_REGS_H */
